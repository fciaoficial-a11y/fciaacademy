## Bloco 1 — O que é IA aplicada no contexto profissional

Esqueça, por um momento, os filmes de ficção científica. No mundo real e produtivo, **Inteligência Artificial é um assistente digital** que entende o que você pede em linguagem natural e devolve resultados úteis: um texto, uma imagem, um roteiro, uma ideia, uma análise.

A IA generativa — a que vamos usar neste curso — funciona como um **profissional polivalente** disponível 24 horas por dia. Ela não substitui você; ela **amplifica** o que você já sabe fazer.

**IA aplicada** é diferente de IA como conceito. Aplicada significa três coisas simultâneas:

1. **Um objetivo profissional claro** (vender mais, produzir conteúdo, atender melhor, decidir mais rápido).
2. **Uma ferramenta certa** para aquela tarefa (texto, imagem, organização, análise).
3. **Um processo repetível** que você consegue executar toda semana, sem depender de inspiração.

Pense na IA como:

- Um **redator** que nunca fica sem ideias.
- Um **designer** que entrega rascunhos em segundos.
- Um **estrategista** que estrutura raciocínios complexos.
- Um **consultor** que sugere caminhos quando você trava.

O segredo não está na ferramenta. Está em **quem conduz** — e em ter um sistema, não só curiosidade.

