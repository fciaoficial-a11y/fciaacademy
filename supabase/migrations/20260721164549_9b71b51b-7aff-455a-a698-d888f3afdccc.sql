## Bloco 5 — Como pensar com IA sem travar

O erro mais comum de quem começa é abrir a ferramenta e pedir *"me ajuda"*. IA não é caixinha mágica — ela é **espelho da sua clareza**.

Adote esta lógica em 3 passos, sempre nesta ordem:

1. **Contexto** — Diga quem você é, para quem fala e o que quer alcançar.
2. **Objetivo** — Descreva o resultado esperado (formato, tamanho, tom).
3. **Referência** — Traga exemplos, dados ou um estilo que sirva de norte.

Quando você entrega contexto, objetivo e referência, a IA deixa de ser genérica e passa a ser **estratégica**.

> Regra de ouro: quanto mais claro o pedido, mais valioso o resultado.

