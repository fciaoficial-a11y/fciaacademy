## ⚠️ Erros comuns que você vai evitar

- **Achar que IA é só ferramenta técnica.** Ela é ferramenta de pensamento e comunicação.
- **Usar IA como curiosidade e esperar resultado de sistema.** Sem rotina, não há acúmulo.
- **Querer automatizar tudo sem direção.** Automação sem estratégia gera ruído, não resultado.
- **Usar IA sem objetivo claro.** Sem alvo, qualquer resposta parece boa — e nenhuma é ótima.
- **Esperar resultado sem contexto.** Prompt vago = entrega genérica. Contexto = entrega valiosa.
- **Testar 5 ferramentas ao mesmo tempo.** Dominar uma vale mais do que tocar em cinco.

Guarde estes pontos. Eles voltam em cada módulo, sob formas diferentes.

