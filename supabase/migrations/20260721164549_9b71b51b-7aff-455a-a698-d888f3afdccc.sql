## Bloco 9 — Como usar IA com intenção e clareza

Usar IA bem é uma **postura profissional**, não um truque técnico. Veja os princípios que vão te acompanhar durante todo o curso:

- **Direção antes de execução.** Pense primeiro no que você quer comunicar; só depois abra a ferramenta.
- **Iteração vale mais que perfeição.** O primeiro resultado é ponto de partida, não de chegada.
- **Curadoria é sua marca.** A IA propõe; você refina, edita e assina.
- **Ética e voz própria.** Use a IA para acelerar o que já é seu — não para copiar o que é dos outros.

Quem domina esses princípios sai da posição de *usuário curioso* e entra na de **profissional que usa IA com autoridade**.

