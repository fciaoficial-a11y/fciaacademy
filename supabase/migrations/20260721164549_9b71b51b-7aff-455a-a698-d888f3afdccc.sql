## Bloco 7 — Prompts prontos para quem está começando

Copie, cole e adapte. Substitua o que estiver `[entre colchetes]` pelo seu contexto real.

**Prompt 1 — Ideias de conteúdo**
```
Aja como um estrategista de conteúdo.
Meu público é [descreva quem é seu cliente ideal].
Minha área é [sua profissão / negócio].
Gere 10 ideias de post curtos que gerem autoridade,
com título chamativo e 1 linha explicando o ângulo de cada um.
```

**Prompt 2 — Post de rede social**
```
Escreva um post para [Instagram/LinkedIn] sobre [tema].
Público: [quem lê].
Objetivo: [educar / atrair cliente / vender].
Tom: direto, próximo, sem jargão.
Formato: abertura forte em 1 linha, corpo com 3 blocos curtos,
fechamento com convite claro para ação.
```

**Prompt 3 — E-mail profissional**
```
Escreva um e-mail para [destinatário e cargo].
Contexto: [situação].
Objetivo do e-mail: [o que eu quero que aconteça].
Tom: profissional, cordial e objetivo. Máx. 120 palavras.
Termine com uma pergunta clara ou próximo passo.
```

**Prompt 4 — Roteiro de vídeo curto (Reels / Shorts)**
```
Crie um roteiro de vídeo de até 45 segundos sobre [tema].
Público: [quem assiste].
Estrutura: gancho nos 3 primeiros segundos,
desenvolvimento em 3 pontos, fechamento com CTA.
Escreva em blocos numerados, com fala e ação em cada bloco.
```

**Prompt 5 — Descrição de produto/serviço**
```
Escreva a descrição de [produto/serviço].
Para quem é: [público].
O que resolve: [dor principal].
O que entrega: [benefícios concretos].
Formato: 1 frase de impacto + 3 bullets de benefício + 1 CTA.
```

**Prompt 6 — Reescrever com sua voz**
```
Reescreva o texto abaixo mantendo a mesma mensagem,
mas com tom [próximo / técnico / editorial / consultivo].
Corte clichês, encurte frases longas e mantenha em
no máximo [X] palavras. Texto: "[cole aqui]".
```

Salve estes prompts em um documento seu. Eles são a **base da sua biblioteca pessoal** — que vai crescer a cada módulo.

