## Bloco 6 — Ferramentas iniciais para começar hoje

Você não precisa de uma pilha de assinaturas. Comece com **três frentes** — texto, imagem e organização — e domine uma ferramenta em cada uma antes de expandir.

**Texto e raciocínio (escolha 1)**
- **ChatGPT** (OpenAI) — o mais versátil para quem começa; ótimo para textos, ideias, e-mails, roteiros.
- **Claude** (Anthropic) — excelente para textos longos, análise de documentos e tom mais editorial.
- **Gemini** (Google) — bem integrado com Docs, Gmail e Drive; útil para quem vive no ecossistema Google.

**Imagem e visual (escolha 1)**
- **ChatGPT com geração de imagem** — o caminho mais simples para começar sem sair de uma única ferramenta.
- **Midjourney** — padrão premium de qualidade visual, ideal para marca e conteúdo editorial.
- **Ideogram / Leonardo** — boas opções gratuitas para artes com texto e composições rápidas.

**Organização e produtividade (escolha 1)**
- **Notion com IA** — para transformar anotações em textos, resumos e planos de ação.
- **Google Docs / Gmail com Gemini** — para escrever e responder mais rápido no que você já usa.
- **Bloco de notas + pasta no Drive** — sim, o mais simples funciona: uma pasta com prompts, textos aprovados e imagens salvas.

**Recomendação prática:** escolha **uma de cada** e use por 30 dias antes de trocar. Pular de ferramenta em ferramenta é o jeito mais rápido de não dominar nenhuma.

