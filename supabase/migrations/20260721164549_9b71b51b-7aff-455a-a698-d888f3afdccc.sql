## Bloco 8 — Template de rotina inicial com IA

Uma rotina simples vale mais que um plano perfeito. Comece com este bloco semanal de **3 sessões curtas**, totalizando cerca de 2 horas.

**🗓 Segunda — Sessão de direção (30 min)**
- Defina o tema da semana.
- Escreva em 1 parágrafo: público, objetivo e mensagem central.
- Gere 10 ideias de conteúdo com o Prompt 1.
- Escolha as 3 melhores.

**🗓 Quarta — Sessão de criação (60 min)**
- Para cada uma das 3 ideias, use os Prompts 2, 4 ou 5.
- Edite com sua voz (regra: 30% IA, 70% você).
- Gere 1 imagem de apoio por peça.
- Salve tudo em uma pasta única da semana.

**🗓 Sexta — Sessão de publicação e revisão (30 min)**
- Publique / envie o material.
- Anote o que funcionou e o que precisa melhorar.
- Guarde os prompts que deram certo na sua biblioteca.

Depois de 4 semanas, você terá: **12 peças publicadas, uma biblioteca própria de prompts e um sistema que roda sozinho**.

