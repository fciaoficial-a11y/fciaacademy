## Bloco 2 — Curiosidade x Sistema de trabalho

A maior parte das pessoas usa IA como **curiosidade**: abre uma vez, pede algo aleatório, se impressiona, fecha, esquece. Isso não muda a vida profissional de ninguém.

Quem tira resultado real usa IA como **sistema de trabalho**. A diferença é grande:

**Modo curiosidade**
- Uso esporádico, sem hora marcada.
- Prompts vagos, tipo "me ajuda com um post".
- Resultado genérico, aproveitado pela metade.
- Nenhum arquivo, nenhum histórico, nenhum aprendizado acumulado.
- Sensação: *"legal, mas não mudou nada"*.

**Modo sistema**
- Uso diário ou semanal, em blocos fixos de tempo.
- Prompts estruturados, com contexto, objetivo e referência.
- Resultado direcionado, editado e publicado.
- Biblioteca própria de prompts, textos e imagens que vão melhorando.
- Sensação: *"produzo em 1 hora o que antes levava 1 semana"*.

> A virada acontece quando você para de *"testar IA"* e começa a **operar com IA** dentro da sua rotina.

Este curso inteiro é desenhado para te colocar no modo sistema desde o Módulo 1.

