## Bloco 4 — Direção humana + execução assistida

Este é o princípio estratégico mais importante do curso inteiro. Guarde:

> **Direção é humana. Execução é assistida.**

O que isso significa na prática?

- **Direção humana** é o que só você pode fazer: definir o público, escolher a mensagem, decidir a proposta de valor, dar tom, aprovar o que sai, assinar o resultado.
- **Execução assistida** é o que a IA faz por você depois que a direção está clara: gerar variações, expandir ideias, montar rascunhos, transformar um formato em outro, ganhar velocidade.

Quando você inverte a lógica — deixa a IA decidir a direção e você só executa — o resultado fica **genérico, sem personalidade e sem autoridade**. É por isso que tanto conteúdo feito com IA parece igual: a pessoa entregou a direção junto com a execução.

O profissional que se destaca opera nesta ordem:

1. **Decide** o que quer comunicar e para quem.
2. **Escreve o prompt** com contexto, objetivo e referência.
3. **Recebe** o rascunho da IA.
4. **Edita, corta e refina** para virar voz própria.
5. **Publica, envia ou apresenta** com nome e cara.

A IA acelera as etapas 2, 3 e 4. As etapas 1 e 5 continuam sendo suas — e é aí que mora a autoridade.

