## Bloco 9 — Como usar IA com intenção comercial

Usar IA bem em vendas é uma **postura profissional**, não um truque técnico. Veja os princípios que vão te acompanhar durante todo o curso:

- **Direção antes de execução.** Pense primeiro no que o cliente precisa ouvir; só depois abra a ferramenta.
- **Personalização real, não cosmética.** Trocar o nome no template não é personalização; refletir a dor real do lead, sim.
- **Iteração vale mais que perfeição.** A primeira mensagem é ponto de partida — refine com dado da resposta.
- **Curadoria é sua marca.** A IA propõe; você refina, edita e assina.
- **Ética e voz própria.** IA para acelerar o que já é seu — não para prometer o que você não entrega.

Quem domina esses princípios sai da posição de *vendedor curioso* e entra na de **operador comercial que usa IA com autoridade**.

