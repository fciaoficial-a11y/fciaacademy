## Bloco 3 — Frameworks de diagnóstico assistidos por IA

Escolha um framework e treine com IA antes de cada call importante.

**SPIN — Situação, Problema, Implicação, Necessidade**
- Perguntas de **Situação** revelam o contexto operacional.
- Perguntas de **Problema** puxam a dor.
- Perguntas de **Implicação** ampliam o custo do problema.
- Perguntas de **Necessidade** conduzem à solução.

**GAP — onde está × onde quer chegar**
- Diagnóstico do estado atual (realidade dura).
- Definição do estado desejado (visão clara).
- Mapeamento da distância (custo, tempo, risco).
- Sua oferta como ponte concreta.

**RCD — Realidade, Consequência, Direção**
- **Realidade**: o que está acontecendo hoje, com números.
- **Consequência**: o que isso custa se continuar.
- **Direção**: para onde a decisão precisa apontar.

IA ajuda montando o roteiro adaptado ao lead. Você conduz a conversa.

