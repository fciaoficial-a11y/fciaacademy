## Bloco 9 — Kickoff e retenção: onde a venda continua

Cliente que assina não é cliente fidelizado. **Retenção** e **expansão** valem tanto quanto novos negócios — e custam menos.

Rotina básica pós-venda:

1. **Kickoff em até 5 dias úteis** com ata (Prompt 3).
2. **Checkpoint quinzenal** durante o contrato (Prompt 6).
3. **Relatório de valor** a cada 90 dias mostrando o que foi entregue.
4. **Conversa de renovação/expansão** 60 dias antes de qualquer vencimento.

Cliente que enxerga entrega concreta **renova** e **indica**. Cliente que só recebe fatura mensal cancela na primeira crise.

