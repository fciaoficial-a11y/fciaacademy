## Bloco 5 — O momento do fechamento

Fechamento não é *"e aí, fecha?"*. Fechamento é **quando você reduz o custo psicológico de dizer sim**. Isso se faz assim:

1. **Resumir a decisão** com clareza — mostrar que os dois sabem o que está sendo decidido.
2. **Explicitar o próximo passo** operacional (assinatura, primeiro pagamento, kickoff).
3. **Reduzir risco** (garantia, teste, milestone, condição).
4. **Convidar** — não pressionar. "Faz sentido seguirmos por aqui na sexta?" vale mais que "podemos fechar?".

Se o cliente diz **não** no fechamento, quase sempre a venda foi perdida no diagnóstico, não no fechamento. Anote onde.

