## Bloco 3 — Onde a IA entra no funil de vendas

A IA é útil em praticamente qualquer etapa que envolva **pesquisar, escrever, argumentar ou organizar**. Veja onde ela entra com mais força:

**Prospecção e pesquisa**
- Levantar contexto do lead em minutos (site, LinkedIn, notícias).
- Mapear dor provável antes do primeiro contato.
- Gerar lista de perguntas de descoberta personalizadas.
- Rascunhar mensagem de abordagem no tom certo.

**Reunião e diagnóstico**
- Resumir call e extrair dores, objeções e próximos passos.
- Estruturar SPIN, GAP ou RCD com base na conversa real.
- Preparar respostas para objeções antecipadas.

**Proposta e fechamento**
- Rascunhar proposta comercial em minutos, com formato editorial.
- Personalizar cada bloco com o vocabulário do cliente.
- Gerar variações de preço, escopo e condições.

**Follow-up e reativação**
- Cadência de mensagens em 3, 7 e 14 dias, sem soar ansioso.
- Reengajamento de base fria com contexto atualizado.
- Texto para reativar cliente antigo com motivo real.

Em outras palavras: **onde há palavra, decisão ou relacionamento, há espaço para IA no comercial**.

