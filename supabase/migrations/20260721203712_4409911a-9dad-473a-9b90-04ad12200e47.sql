## Bloco 2 — Anatomia de uma pesquisa de lead com IA

Uma boa pesquisa comercial responde 5 perguntas antes do primeiro contato:

1. **O que a empresa faz** (em 1 parágrafo, sem jargão).
2. **Qual é o momento dela** (crescimento, reestruturação, expansão, corte).
3. **Qual é a dor provável** ligada ao seu produto/serviço.
4. **Quem é a pessoa** (cargo, escopo, sinais no perfil).
5. **Qual é o gancho** — o dado ou frase que só cabe nesse lead.

IA responde as 5 se você entregar boas fontes: link do site, link do LinkedIn, notícias recentes. Sem input, ela chuta — e chute em vendas é o caminho mais curto para o "não obrigado".

