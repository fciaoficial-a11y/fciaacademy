- Após 90 dias, rodou Prompt 2 e viu: taxa de resposta boa (18%), taxa de proposta ruim (28%). Gargalo estava na **conversão de call para proposta**.
- Experimento: mudou roteiro de call, incluiu mapeamento de decisor logo no início.
- Trimestre seguinte: taxa de proposta subiu para **41%**, ticket médio subiu 22%, ciclo caiu 9 dias.

Larissa não trabalhou mais. Ela **trabalhou com direção**. IA cuidou do que virava rotina; ela cuidou da estratégia.

