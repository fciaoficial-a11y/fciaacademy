## Bloco 3 — Cadência de follow-up sem ansiedade

Follow-up ruim é aquele que diz *"só passando aqui"*. Follow-up bom sempre traz algo: um insight, uma pergunta, um dado novo, um recorte relevante.

Cadência mínima recomendada:

**Dia 0** — proposta enviada.
**Dia 3** — pergunta objetiva sobre alguma parte específica da proposta.
**Dia 7** — insight ou material complementar que **agrega e não empurra**.
**Dia 14** — reabertura com pergunta que faz sentido mesmo se ele estiver frio.
**Dia 30** — reativação com contexto novo, sem cobrar decisão.

Cada mensagem tem função. Nenhuma repete a anterior. Nenhuma pergunta *"e aí?"*.

