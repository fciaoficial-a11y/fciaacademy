## Bloco 5 — Como priorizar leads com IA

Priorização ruim mata pipeline. IA ajuda com um critério simples: **probabilidade × esforço × valor**.

Para cada lead ativo, avalie:

- **Probabilidade** (0-10): quanto ele parece decidir em 30 dias.
- **Esforço** (0-10): quanta energia sua ele ainda vai exigir.
- **Valor** (0-10): quanto vale se fechar.

Score de foco = **(Probabilidade × Valor) / Esforço**. Leads acima da média ganham prioridade da semana. Leads muito abaixo entram para reativação futura.

IA rodando esse cálculo com base no resumo do lead economiza horas de dúvida.

