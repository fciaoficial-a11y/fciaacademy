## Bloco 5 — Como pensar a abordagem sem template

Abordagem que funciona respeita 4 camadas, sempre nesta ordem:

1. **Gancho específico** — algo público e recente que mostra que você olhou de verdade.
2. **Ponte para o problema** — de forma consultiva, não vendedora.
3. **Valor claro** — o que você pode oferecer, em 1 frase objetiva.
4. **Convite pequeno** — não venda a solução, venda a próxima conversa.

Cliente não recusa curiosidade. Ele recusa pressão. Sua abordagem precisa provocar interesse, não decisão.

> Regra de ouro: se a mesma mensagem serve para outro lead, ela ainda não está pronta.

