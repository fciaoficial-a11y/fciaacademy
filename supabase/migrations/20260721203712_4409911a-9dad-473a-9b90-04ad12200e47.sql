## Bloco 1 — O que é venda assistida por IA

Esqueça, por um momento, o vendedor que dispara mensagem em massa. No mundo real e produtivo, **venda com IA é diagnóstico assistido**: você entende o cliente melhor, mais rápido e com mais profundidade do que qualquer concorrente que ainda opera no improviso.

A IA generativa — a que vamos usar neste curso — funciona como um **analista comercial** disponível 24 horas por dia. Ela não fecha a venda por você; ela **amplifica** cada etapa do processo que você já executa.

**Venda assistida** é diferente de "usar ChatGPT para escrever um e-mail". Assistida significa três coisas simultâneas:

1. **Um objetivo comercial claro** (agendar reunião, avançar proposta, reativar cliente, aumentar ticket).
2. **Uma ferramenta certa** para aquela tarefa (pesquisa, mensagem, resumo, argumentação).
3. **Um processo repetível** que você executa toda semana, sem depender de inspiração.

Pense na IA como:

- Um **pesquisador** que nunca dorme e vasculha o lead antes da call.
- Um **redator** que produz proposta em minutos, no seu tom.
- Um **estrategista** que estrutura argumento contra objeção específica.
- Um **coach** que revisa seu discurso e aponta o que enfraquece a venda.

O segredo não está na ferramenta. Está em **quem conduz** — e em ter um sistema, não só entusiasmo.

