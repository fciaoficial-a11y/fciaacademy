## Bloco 5 — Como pensar com IA sem travar na venda

O erro mais comum de quem começa é abrir a ferramenta e pedir *"escreve um texto para meu cliente"*. IA não é caixinha mágica — ela é **espelho da clareza que você tem sobre o lead**.

Adote esta lógica em 3 passos, sempre nesta ordem:

1. **Contexto** — Quem é o lead, o que ele faz, qual dor provável, em que etapa do funil está.
2. **Objetivo** — O que essa mensagem/proposta precisa provocar (resposta, reunião, decisão).
3. **Referência** — Um exemplo, tom, formato ou peça que sirva de norte.

Quando você entrega contexto, objetivo e referência, a IA deixa de ser genérica e passa a ser **estratégica** — e o cliente sente diferença já na primeira frase.

> Regra de ouro: quanto mais claro o pedido, mais fácil o "sim".

