## Bloco 2 — Curiosidade x Sistema comercial

A maior parte dos vendedores usa IA como **curiosidade**: abre uma vez, pede um "texto para cliente", copia, cola, se impressiona, esquece. Isso não muda faturamento de ninguém.

Quem tira resultado real usa IA como **sistema comercial**. A diferença é gritante:

**Modo curiosidade**
- Uso esporádico, quando "trava" a proposta.
- Prompts vagos, tipo "escreve um e-mail de vendas".
- Resultado genérico, aproveitado pela metade, sem personalização real.
- Nenhum arquivo de leads, nenhum histórico, nenhum aprendizado acumulado.
- Sensação: *"legal, mas meu pipeline continua igual"*.

**Modo sistema**
- Uso diário em blocos fixos: pesquisa, mensagem, follow-up.
- Prompts estruturados, com contexto do lead, etapa do funil e objetivo da interação.
- Resultado direcionado, editado com sua voz, enviado no tempo certo.
- Biblioteca própria de prompts, mensagens e argumentos que vão melhorando.
- Sensação: *"faço em 1 hora o pipeline que antes levava a semana toda"*.

> A virada acontece quando você para de *"testar IA para vender"* e começa a **operar vendas com IA** dentro da sua rotina comercial.

