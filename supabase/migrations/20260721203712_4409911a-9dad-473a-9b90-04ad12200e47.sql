## Bloco 10 — Como iterar o processo com IA

A cada 90 dias, faça a **revisão profunda** do seu comercial:

- Rode Prompt 2 sobre os últimos 3 meses.
- Compare com trimestre anterior.
- Identifique **1 gargalo real** (não 5).
- Escolha **1 experimento** para os próximos 90 dias (novo canal, novo segmento, novo tipo de proposta).
- Mede resultado ao final.

Iteração vence perfeição. Vendedor que testa 1 hipótese por trimestre supera qualquer método fechado — porque ajusta ao mercado real.

