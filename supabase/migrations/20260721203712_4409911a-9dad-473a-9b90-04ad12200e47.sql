## Bloco 1 — O que é objeção na prática

Objeção aparece em 3 formas — e cada uma pede resposta diferente:

**Objeção racional**
- "Está caro." / "Não tenho orçamento." / "Preciso comparar."
- Reação certa: **dado, número, comparação, retorno esperado**.

**Objeção emocional**
- "Preciso pensar." / "Não é o momento." / "Vou levar pro time."
- Reação certa: **empatia, história curta, redução de risco**.

**Objeção estratégica**
- "Já temos fornecedor." / "Não é prioridade." / "Estamos em outra fase."
- Reação certa: **pergunta que reposiciona, provocação consultiva**.

Confundir o tipo é o erro mais comum. Responder emoção com planilha ou razão com abraço destrói venda.

