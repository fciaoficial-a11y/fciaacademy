## ⚠️ Erros comuns que você vai evitar

- **Pipeline em cabeça, não em planilha.** O que não está escrito, não existe.
- **Vender sem funil claro.** Sem etapa, sem previsão.
- **Sem indicador, com achismo.** Achar não vende — dado sim.
- **Ferramenta antes de processo.** CRM caro não substitui rotina.
- **Sumir depois do fechamento.** Cliente sem checkpoint é cliente que sai.
- **Experimentar 5 coisas ao mesmo tempo.** 1 hipótese por vez, medida por 90 dias.

