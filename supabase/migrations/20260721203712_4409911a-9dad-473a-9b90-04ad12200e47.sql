## Bloco 4 — Direção humana + execução assistida

Este é o princípio estratégico mais importante do curso inteiro. Guarde:

> **Direção é humana. Execução é assistida.**

O que isso significa na prática comercial?

- **Direção humana** é o que só você pode fazer: escolher o segmento, ler o cliente entre linhas, decidir a estratégia, dar tom, aprovar o que sai e assinar a proposta.
- **Execução assistida** é o que a IA faz por você depois que a direção está clara: gerar variações, estruturar argumento, montar rascunhos, transformar reunião em resumo, ganhar velocidade.

Quando você inverte a lógica — deixa a IA escolher o ângulo e você só copia — o resultado fica **genérico, sem autoridade e fácil de recusar**. É por isso que tanta mensagem comercial feita com IA parece igual: o vendedor entregou a direção junto com a execução.

O vendedor que se destaca opera nesta ordem:

1. **Decide** com quem quer falar e o que quer alcançar naquela etapa.
2. **Escreve o prompt** com contexto do lead, objetivo da interação e referência.
3. **Recebe** o rascunho da IA.
4. **Edita, corta e refina** para virar voz própria e falar com aquele lead específico.
5. **Envia, apresenta ou negocia** com nome, cara e responsabilidade.

A IA acelera as etapas 2, 3 e 4. As etapas 1 e 5 continuam sendo suas — e é aí que mora a autoridade comercial.

