Ferramentas mudam. Método permanece. Neste módulo você aprende a decidir a direção criativa **antes** de gerar qualquer imagem, vídeo ou trilha. Um roteiro é a primeira aplicação do Ciclo FCIA (Ler → Pensar → Criar → Encantar → Vender → Revisar) sobre texto — e ele define se o audiovisual final terá alma ou parecerá mais um post de IA.

## Objetivo do módulo

Sair da aula com um **roteiro audiovisual de 60 a 90 segundos** estruturado em beats, com abertura, tensão, virada, prova e fechamento. Este roteiro será a base de execução dos M3 ao M6 — imagem, vídeo, som e integração — para o mesmo projeto-guia.

Você aprende a:

- ler um briefing e extrair a **promessa única** da peça;
- decidir tom, ritmo e emoção antes de escrever;
- estruturar em beats que sustentam atenção do segundo 1 ao 90;
- traduzir cada beat em direção visual e sonora explícita;
- escrever o roteiro de forma que IA execute com intenção — não com aleatoriedade.

## Exemplo prático

Briefing real: uma marca de café especial precisa de um filme de 75s para lançar um novo blend. Sem método, o aluno pediria "faça um vídeo bonito de café" e receberia genérico. Com o Ciclo FCIA, ele produz um roteiro assim:

- **Beat 1 — Abertura (0–8s):** close extremo em grãos torrando. Silêncio. Um estalo. **Promessa nasce do detalhe.**
- **Beat 2 — Contexto (8–25s):** narrador em tom de crônica apresenta o produtor real. Emoção antes de produto.
- **Beat 3 — Tensão (25–45s):** por que a maioria dos cafés perde alma na escala? Contraste visual entre indústria e artesanal.
- **Beat 4 — Virada (45–60s):** o blend nasce como resposta. Imagem, som e narrativa convergem.
- **Beat 5 — Prova (60–70s):** cliente real, xícara, primeira reação. Silêncio outra vez.
- **Beat 6 — Fechamento (70–75s):** logotipo, promessa em uma linha, CTA suave.

Cada beat vira briefing para imagem (M3), vídeo (M4) e som (M5). O roteiro **não descreve tudo** — ele **decide**. Direção antes de execução.

## Erros comuns

- **Escrever roteiro como legenda de Instagram.** Roteiro audiovisual tem beats, ritmo e cortes. Não é texto corrido.
- **Deixar a IA decidir a estrutura.** IA executa bem quando o humano decide antes. Sem beats, o resultado é média genérica.
- **Confundir tom com estilo visual.** Tom é emoção-alvo (nostalgia, urgência, contemplação). Estilo visual vem depois, a serviço do tom.
- **Não escrever em tempo.** Se o beat não tem duração explícita, o vídeo estica ou corta no lugar errado.
- **Terminar com "saiba mais".** Todo fechamento precisa de uma promessa curta e uma ação clara.

## Fechamento

Roteiro é o esqueleto do audiovisual. Sem ele, imagem, vídeo e som brigam entre si. Com ele, os quatro elementos convergem para a mesma emoção. A partir deste módulo, todo projeto começa por escrito — mesmo que dure 15 segundos.

**Checkpoint verificável (entrega do M2):** um roteiro de 60–90s do seu projeto-guia, dividido em 5 a 7 beats, com duração explícita, tom emocional definido e uma linha de direção visual e sonora por beat. Este documento vira o briefing dos próximos quatro módulos.

