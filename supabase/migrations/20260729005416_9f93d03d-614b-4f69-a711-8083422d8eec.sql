No M3 você definiu **como o projeto se parece**. Neste módulo o projeto começa a **se mover**. Vídeo com IA não é gerar clipes soltos — é dirigir tempo, ritmo e emoção sobre os beats do roteiro, mantendo o kit visual do M3 vivo em cada plano. Esta é a fase **Criar → Encantar** do Ciclo FCIA aplicada ao movimento: primeiro se decide o que cada segundo precisa provocar, depois se gera.

## Objetivo do módulo

Sair da aula com uma **sequência de vídeo de 60 a 90 segundos** do projeto-guia, montada a partir dos beats do M2 e do kit visual do M3, com continuidade de identidade entre planos e um ritmo emocional legível.

Você aprende a:

- traduzir cada beat do roteiro em **intenção de plano** — o que a câmera precisa fazer sentir, não só mostrar;
- escolher entre **image-to-video, text-to-video e keyframes** conforme o beat pede estabilidade, gesto ou transformação;
- escrever prompt de movimento com **verbo dominante, duração e direção de câmera** — não adjetivos soltos;
- manter **continuidade visual** entre planos gerados em ferramentas diferentes (paleta, lente, grão, mood do M3);
- costurar os planos em um corte com **respiro, ênfase e clímax**, no lugar de sequência plana.

## Exemplo prático

Retomando o filme do café. Beat 1 pede close extremo, silêncio, promessa no detalhe. Sem método, o aluno pede "vídeo cinematográfico de café" e recebe uma câmera girando sem propósito. Com direção:

- **Intenção do plano 1 (0:00–0:04):** micro-movimento, quase estático. A câmera **respira**, não anda. Grãos ao centro, vapor lento subindo. Emoção: expectativa contida.
- **Prompt dirigido (image-to-video sobre a imagem final do M3):** "câmera parada, respiração sutil, vapor subindo lentamente da direita para a esquerda, foco mantido no grão central, sem paneo, sem zoom, duração 4s, 24fps, mesma paleta âmbar e grão fotográfico da imagem-base."
- **Beat 3 — plano industrial:** troca a intenção para "movimento mecânico contínuo, paneo lateral lento da esquerda para a direita, linha de produção em foco médio, luz fria estável, 4s". Mesma régua, outra emoção — o corte entre os planos **conta a história sozinho**.
- **Costura:** três planos de 4s (contemplativo → mecânico → humano) com respiro de 0.5s entre cortes. Sem música ainda, mas a estrutura emocional já está de pé.

## Erros comuns

- **Gerar sem beat.** Pedir "vídeo bonito de X" produz vídeo genérico. Beat sem intenção = plano sem função.
- **Trocar de estilo a cada plano.** Ferramenta diferente é aceitável; **paleta, lente e grão diferentes não são.** Continuidade separa peça autoral de colagem de IA.
- **Movimento em tudo.** Se todos os planos se movem, nenhum se destaca. Plano estático é **ferramenta narrativa**, não erro.
- **Ignorar duração.** Prompt sem duração explícita gera clipes de tamanho aleatório que quebram o ritmo do corte.
- **Cortar seco.** Sem respiro entre planos, o cérebro do espectador sente pressa em vez de emoção.

## Fechamento

Vídeo com IA em nível profissional não é sobre a ferramenta gerar cenas espetaculares. É sobre **você decidir o que cada segundo precisa provocar** e usar a ferramenta como câmera dirigida. Quando o beat, a intenção do plano e a régua visual estão claros, o vídeo deixa de ser um efeito e passa a ser uma peça — com autor, ritmo e continuidade.

## Checkpoint prático

**Entrega verificável desta aula:**

1. Selecione 3 a 6 beats do roteiro do M2 que se sustentam como sequência.
2. Para cada beat, escreva a **intenção do plano em uma linha** (o que a câmera precisa fazer sentir).
3. Escolha o método: image-to-video (sobre a imagem final do M3), text-to-video ou keyframes.
4. Gere cada plano com prompt dirigido — verbo dominante, duração explícita, direção de câmera, paleta e grão do M3.
5. Monte um corte de **60 a 90 segundos** com respiro entre planos.
6. Assista sem som. Se a sequência **ainda transmite a emoção do roteiro**, o módulo está entregue.

