## Objetivo do módulo

Ao final desta aula você vai:

- entender por que IA sem método vira ruído
- dominar as 6 fases do Ciclo FCIA: **Ler, Pensar, Criar, Encantar, Vender, Revisar**
- aplicar o ciclo a um caso real (mesmo sem ferramenta aberta)
- entregar seu **Manifesto Criativo** — o documento que guia todas as próximas 9 aulas

O ciclo não muda. O que muda é a mídia, o contexto e a profundidade em cada módulo.

## O problema real: por que 95% das pessoas usam IA errado

A maioria abre uma ferramenta de IA, digita um pedido, olha o resultado e pensa: "não é bem isso". Tenta de novo. Ajusta uma palavra. Reclama que "a IA é limitada".

O erro nunca esteve na IA. Está no **processo**.

Sem método, você entrega à IA a decisão criativa — que é justamente a parte que **não deve** ser terceirizada. IA executa. Direção criativa é sua. Confundir os dois papéis é o que gera output medíocre, genérico, sem identidade.

Um profissional criativo com IA não pergunta "o que a IA consegue fazer?". Pergunta: **"o que eu quero comunicar, para quem, com qual emoção, com qual identidade — e como uso IA para executar isso?"**

## O Ciclo Criativo FCIA

Seis fases. Aplicadas em toda peça, todo módulo, toda entrega.

**1. Ler** — decifrar o briefing, o público e o problema real. Antes de criar, você entende. Quem consome? Qual dor? Qual desejo? Qual contexto de uso?

**2. Pensar** — definir direção criativa **antes** de tocar em qualquer ferramenta. Conceito, emoção-alvo, referências visuais, tom. Isso vira instrução para a IA — não sugestão.

**3. Criar** — executar com IA (texto, imagem, vídeo, som). Aqui a ferramenta entra. Você prompta com direção clara, não com desejo vago.

**4. Encantar** — refinar identidade, emoção e coerência. O primeiro output raramente é o final. Você itera com critério, não com sorte.

**5. Vender** — transformar a peça em ativo de mercado. Toda criação existe para gerar resultado: atenção, conversão, autoridade, receita.

**6. Revisar** — extrair aprendizado. O que funcionou? O que vira template? O que descartar? Cada peça alimenta a próxima.

## Exemplo prático: aplicando o ciclo a um post de Instagram

Suponha um briefing: "post para lançar uma consultoria de branding para pequenos negócios".

- **Ler:** público = donos de negócios entre 30–50 anos, sensíveis a preço mas cansados de marcas amadoras. Dor real: "minha marca parece fraca". Desejo: parecer profissional sem gastar fortuna.
- **Pensar:** direção = contraste antes/depois. Emoção-alvo = "eu finalmente pareço sério". Tom = firme, sem hype. Paleta = neutra + um acento vivo.
- **Criar:** prompt para IA de imagem entregando o contraste com identidade definida. Copy escrita a partir da dor, não a partir da oferta.
- **Encantar:** ajustar tipografia, cortar palavras genéricas, refinar composição até parecer da marca — não da IA.
- **Vender:** CTA claro, link direto, oferta com prazo.
- **Revisar:** métrica coletada em 72h. Template do que funcionou salvo para o próximo lançamento.

Note: apenas **uma** das seis fases usa IA. As outras cinco são decisão criativa sua.

## Erros comuns neste módulo

- **Pular a fase Ler.** Você entra direto no prompt e a IA vira adivinha.
- **Confundir Pensar com prompt.** Direção criativa vem antes do prompt. Prompt é a tradução da direção — não o lugar onde ela nasce.
- **Aceitar o primeiro output.** Se o primeiro resultado da IA já parece suficiente, provavelmente ele está genérico.
- **Terceirizar identidade.** Se qualquer concorrente pode gerar a mesma peça com o mesmo prompt, você não criou — copiou.
- **Ignorar Revisar.** Sem revisão, você refaz o mesmo processo do zero toda semana em vez de construir um sistema.

## Checkpoint: seu Manifesto Criativo

Antes de avançar para o Módulo 2, produza um documento curto (1 página) respondendo:

1. **Quem sou eu como criativo?** Uma frase de posicionamento.
2. **Para quem eu crio?** Público-alvo em uma frase clara, sem "todo mundo".
3. **Qual promessa eu entrego?** Transformação concreta, não característica.
4. **Qual emoção-raiz atravessa meu trabalho?** Uma palavra.
5. **Qual é minha assinatura visual e verbal?** Três referências + três palavras.
6. **Qual resultado de mercado eu busco nos próximos 90 dias?** Meta específica.

