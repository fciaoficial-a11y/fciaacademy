## Bloco 4 — Títulos e ganchos: onde a leitura começa (ou morre)

Um bom conteúdo com um título fraco é como um restaurante ótimo sem fachada: **ninguém entra**. O título e o gancho são responsáveis por até **80% da leitura** de qualquer peça.

Fórmulas testadas que a IA executa muito bem quando você pede com contexto:

- **Contraste**: *"O que ninguém te disse sobre X (e está travando seu Y)"*
- **Erro comum**: *"3 erros que fazem seu conteúdo passar batido"*
- **Atalho**: *"Como fazer X em menos de Y minutos"*
- **Curiosidade específica**: *"O detalhe de 10 segundos que muda a percepção do cliente"*
- **Prova**: *"Como saí de X para Y usando apenas Z"*

**Prompt sugerido para IA:**
> "Gere 10 títulos no estilo *contraste + curiosidade específica*, para um post sobre [tema], voltado para [público], com tom [profissional/direto/inspirador]. Máximo 12 palavras cada."

Peça sempre **em lote**. Escolher entre 10 é infinitamente melhor do que aceitar o primeiro.

