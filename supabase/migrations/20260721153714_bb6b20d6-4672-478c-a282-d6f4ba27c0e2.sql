## Bloco 3 — Como conduzir a IA para gerar imagens com identidade

Pedir *"uma imagem bonita sobre marketing"* devolve exatamente o que você imagina: **algo genérico**. A IA de imagem responde ao mesmo princípio da IA de texto — ela é o espelho da sua clareza.

Use esta estrutura de prompt visual em 4 camadas:

1. **Sujeito** — o que aparece no centro (pessoa, objeto, cena).
2. **Estilo** — fotografia realista, editorial, cinematográfica, minimalista, 3D suave, etc.
3. **Atmosfera** — iluminação, cor dominante, sensação (calma, tensa, sofisticada).
4. **Enquadramento** — plano fechado, aberto, ângulo, profundidade.

**Exemplo aplicado:**
> "Retrato editorial de uma profissional brasileira de 35 anos trabalhando em um notebook, luz natural lateral suave, paleta bege e verde oliva, plano médio, fundo desfocado de escritório minimalista, estilo fotografia cinematográfica realista."

Perceba: **nenhuma palavra é decorativa**. Cada camada guia a IA para uma peça com identidade — não uma imagem qualquer.

