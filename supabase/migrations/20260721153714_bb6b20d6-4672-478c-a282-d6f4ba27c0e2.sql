## Bem-vindo ao Módulo 2

Atenção é a moeda mais cara do mundo digital. Se o seu conteúdo não para o dedo do usuário no primeiro segundo, ele simplesmente **não existe** — por melhor que seja o que vem depois. Neste módulo você aprende a criar peças visuais e textuais que **chamam o olho, prendem a leitura e comunicam autoridade**, usando a IA como sua parceira criativa.

> Nosso compromisso aqui: menos "achismo estético", mais **critério visual aplicado**. Ao final, você não vai só *usar* IA para gerar imagens ou textos — vai **conduzir** a IA para produzir peças com intenção, identidade e impacto.

---

## 🎯 Objetivo do Módulo

Ao concluir este módulo, você será capaz de:

- Produzir **conteúdo visual e textual** atraente com IA, sem depender de designer ou copywriter para começar.
- Aplicar os **3 gatilhos de atenção** que fazem alguém parar de rolar o feed.
- Escrever prompts que geram **imagens com identidade**, não genéricas.
- Estruturar **títulos e ganchos** que aumentam leitura e retenção.
- Criar peças com um **padrão visual reconhecível** ao longo do tempo.

