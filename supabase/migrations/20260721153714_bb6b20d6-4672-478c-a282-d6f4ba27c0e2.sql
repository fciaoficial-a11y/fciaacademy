## ⚠️ Erros comuns que travam a atenção

- **Prompt genérico** — pedir "uma imagem sobre X" sem definir estilo, paleta e enquadramento.
- **Excesso de elementos** — tentar dizer 5 coisas no mesmo post. O olho desiste.
- **Título descritivo em vez de instigante** — *"Falando sobre reserva de emergência"* nunca vai competir com *"3 sinais de que sua reserva está errada"*.
- **Mudança de estilo a cada post** — hoje ilustrado, amanhã foto, depois 3D. Isso **apaga** a memória visual.
- **Aceitar o primeiro resultado da IA** — o primeiro é ponto de partida. **Sempre itere.**

