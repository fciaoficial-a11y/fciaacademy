## Bloco 2 — Os 3 gatilhos de atenção que sempre funcionam

Independentemente da rede social, do formato ou do nicho, três gatilhos concentram a maior parte da atenção conquistada:

**1. Contraste visual**
Fundo escuro com elemento claro, tipografia grande sobre imagem calma, cor de destaque em meio a tons neutros. Contraste é o **atalho biológico** para o olho.

**2. Curiosidade guiada**
Frases que **abrem um loop mental**: *"Ninguém te contou isso sobre…"*, *"O erro que trava 9 em cada 10…"*, *"Se eu começasse hoje, faria assim…"*. O cérebro precisa fechar o loop — e para fazer isso, ele **precisa ler**.

**3. Prova de autoridade imediata**
Um número, um resultado, um "antes e depois", um selo, uma frase técnica precisa. Autoridade não é se gabar — é **mostrar domínio em segundos**.

Uma peça de alto impacto costuma combinar **dois desses gatilhos**. Três é raro e, quando bem feito, é o que chamamos de peça viral orgânica.

