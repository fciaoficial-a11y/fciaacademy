## 💡 Exemplo prático — do briefing à peça pronta

Cenário: você é consultora financeira e quer um post que pare o feed com o tema *"3 sinais de que sua reserva de emergência está errada"*.

**Passo 1 — Título** (gatilho: erro comum + curiosidade específica)
> "3 sinais silenciosos de que sua reserva de emergência está errada"

**Passo 2 — Imagem** (prompt visual em 4 camadas)
> "Fotografia editorial realista de mãos femininas escrevendo em um caderno ao lado de um notebook, luz natural lateral, paleta bege e verde oliva, plano fechado sobre a mesa, atmosfera calma e profissional."

**Passo 3 — Gancho de abertura** (para a legenda ou primeiro slide)
> "Você acha que tem reserva. Mas talvez esteja se protegendo do risco errado."

**Passo 4 — Padrão visual mantido**
Mesmas cores, mesma tipografia, mesma respiração dos posts anteriores. **Nada é acidental.**

Resultado: uma peça que **para o dedo, prende a leitura e reforça a sua marca** — sem designer, sem copywriter, em menos de 15 minutos.

