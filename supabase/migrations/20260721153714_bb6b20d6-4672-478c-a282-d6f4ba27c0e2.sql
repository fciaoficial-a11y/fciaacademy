## Bloco 1 — Por que a maioria do conteúdo passa batido

Antes de aprender a chamar atenção, é preciso entender por que quase ninguém consegue. O feed é uma competição silenciosa por **frações de segundo**, e o usuário decide se para ou não com base em três coisas:

- **Cor e contraste** — o olho é atraído por peças que se destacam do ambiente.
- **Rosto e emoção** — expressões humanas geram parada quase automática.
- **Promessa clara** — uma frase que responde *"por que eu deveria olhar isso?"*.

A maioria falha porque produz peças **bonitas, mas mudas**: sem foco, sem promessa, sem hierarquia. Beleza sem intenção é decoração — e decoração não vende, não ensina e não conecta.

> Regra prática: se a peça funciona **sem som e sem legenda**, ela tem chance real de parar o dedo.

