## Bloco 5 — Construindo um padrão visual reconhecível

Uma peça bonita chama atenção uma vez. Um **padrão visual** constrói memória. É o padrão que faz alguém dizer *"vi um post seu no feed"* mesmo sem ler o seu nome.

Defina, e mantenha, quatro elementos:

- **Paleta** — 2 cores base + 1 cor de destaque. Só.
- **Tipografia** — 1 fonte para títulos, 1 para corpo. Nunca mais.
- **Composição** — margem generosa, hierarquia clara, respiração visual.
- **Tom da imagem** — sempre editorial, ou sempre ilustrado, ou sempre fotográfico. **Escolha um caminho.**

Peça à IA para gerar variações **dentro do seu padrão**, não fora dele:

> "Mantenha paleta bege, verde oliva e preto, tipografia serifada nos títulos, estilo editorial calmo, com respiração visual generosa. Gere 3 variações do post sobre [tema]."

Consistência é o que separa **quem posta** de **quem tem marca**.

